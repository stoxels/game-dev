function refValue(key, level) {
    const pts = REF[key];
    if (!pts) return 0;
    if (level <= REF_LEVELS[0]) return pts[0] * (0.35 + 0.065 * Math.max(1, level));
    if (level >= REF_LEVELS[REF_LEVELS.length - 1]) return pts[pts.length - 1];
    for (let i = 1; i < REF_LEVELS.length; i++) {
        if (level <= REF_LEVELS[i]) {
            const t = (level - REF_LEVELS[i - 1]) / (REF_LEVELS[i] - REF_LEVELS[i - 1]);
            return pts[i - 1] + (pts[i] - pts[i - 1]) * t;
        }
    }
    return pts[pts.length - 1];
}

function roundFor(key, v) {
    if (FLOAT_KEYS.has(key)) return Math.max(0.1, Math.round(v * 10) / 10);
    return Math.max(1, Math.round(v));
}

