const LOCAL_DEFENSE_KEYS = { flat_armour: 'armour', inc_armour: 'armour', flat_evasion: 'evasion', inc_evasion: 'evasion', flat_absorption: 'absorption', inc_absorption: 'absorption' };
const JEWELRY = new Set(['ring', 'earring', 'amulet', 'talisman']);

function poolFor(def) {
    const slot = def.slotType;
    const d = def.defenses || {};
    if (slot === 'weapon') return POOLS.weapon;
    if (slot === 'ranged') return POOLS.ranged;
    if (slot === 'arcane') return POOLS.arcane;
    if (slot === 'shield') return (d.armour || 0) >= (d.absorption || 0) ? POOLS.shield : POOLS.shieldAbs;
    if (JEWELRY.has(slot)) {
        if (def.archetype === 'strength') return POOLS.jewelStr;
        if (def.archetype === 'agility') return POOLS.jewelAgi;
        return POOLS.jewelInt;
    }
    const arm = d.armour || 0, eva = d.evasion || 0, abs = d.absorption || 0;
    if (def.archetype === 'strength' && arm) return POOLS.tank;
    if (def.archetype === 'agility' && eva) return POOLS.evade;
    if (def.archetype === 'intellect' && abs) return POOLS.caster;
    if (eva >= arm && eva >= abs && eva) return POOLS.evade;
    if (abs > arm && abs >= eva) return POOLS.caster;
    return POOLS.tank;
}

function scaledKeep(orig, level) {
    const key = orig.key;
    const ref = refValue(key, level);
    let v = orig.value;
    if (key === 'attack_speed' && v > 3) v = 0.7 * ref;          // legacy percent-style values
    else if (ref) v = Math.min(Math.max(v, 0.8 * ref), 1.3 * ref);
    else v = v * 1.3;
    return { key, value: roundFor(key, v), en: orig.en, de: orig.de };
}

function fillerLine(key, frac, level) {
    const lab = LABELS[key];
    return { key, value: roundFor(key, refValue(key, level) * frac), en: lab[0], de: lab[1] };
}

function makeDownside(spec, level) {
    const [key, fracStr] = spec.split(' ');
    const frac = Number(fracStr);
    const ref = refValue(key, level);
    const value = -roundFor(key, ref * Math.abs(frac));
    const lab = NEG_LABELS[key] || LABELS[key];
    return { key, value, en: lab[0], de: lab[1] };
}

// Applies a compact entry to a def; pushes problems (unknown keep keys).
function generateStats(def, entry, problems) {
    const [roleCode, keepStr, fxStr, dnStr, tweaks] = entry;
    const level = def.minLevel || 1;
    const orig = def.bonuses || [];
    const lines = [];
    for (const key of (keepStr || '').split(' ').filter(Boolean)) {
        const o = orig.find(b => b.key === key);
        if (!o) { problems.push(`${def.uniqueId}: keep key "${key}" not on the original unique`); continue; }
        // Local defense mods only work on a matching base defense; a few old
        // uniques carried dead lines (e.g. flat Armour on an Evasion cloak).
        const localKind = LOCAL_DEFENSE_KEYS[key];
        if (localKind && !((def.defenses || {})[localKind] > 0)) continue;
        lines.push(scaledKeep(o, level));
    }
    let downside = dnStr ? makeDownside(dnStr, level) : null;
    const taken = new Set(lines.map(l => l.key));
    if (downside) taken.add(downside.key);
    const d = def.defenses || {};
    for (const [key, frac] of poolFor(def)) {
        if (lines.length >= STAT_LINES[roleCode]) break;
        if (taken.has(key)) continue;
        if ((key === 'inc_armour' || key === 'flat_armour') && !d.armour) continue;
        if ((key === 'inc_evasion' || key === 'flat_evasion') && !d.evasion) continue;
        if (key === 'inc_absorption' && !d.absorption) continue;
        lines.push(fillerLine(key, frac, level));
        taken.add(key);
    }
    if (tweaks && tweaks.set) {
        for (const k of Object.keys(tweaks.set)) {
            const line = lines.find(l => l.key === k);
            if (line) line.value = tweaks.set[k]; else problems.push(`${def.uniqueId}: tweak key "${k}" has no line`);
        }
    }
    if (tweaks && tweaks.down) {
        const [dk, dv] = tweaks.down;
        const lab = NEG_LABELS[dk] || LABELS[dk];
        downside = { key: dk, value: dv, en: lab[0], de: lab[1] };
    }
    def.bonuses = lines;
    def.effects = (fxStr || '').split(' ').filter(Boolean);
    def.downsides = downside ? [downside] : [];
    def.role = ROLE_NAMES[roleCode];
    def.v2 = true;
}

// Raises base defenses / damage / block to the best regular base of the slot
// and level (the old uniques sat far below it).
function levelOfBase(b) { return (b.requirements && b.requirements.level) || b.minLevel || 1; }

function upgradeBase(def) {
    const level = (def.minLevel || 1) + 2;
    const bases = EG_ALL_BASE_TYPES.filter(b => b.slotType === def.slotType && levelOfBase(b) <= level);
    if (!bases.length) return;
    if (def.defenses) {
        const kinds = ['armour', 'evasion', 'absorption'].filter(k => def.defenses[k] > 0);
        const exact = bases.filter(b => b.defenses && kinds.every(k => b.defenses[k] > 0)
            && ['armour', 'evasion', 'absorption'].every(k => kinds.includes(k) || !(b.defenses[k] > 0)));
        const best = exact.sort((a, b) => levelOfBase(b) - levelOfBase(a))[0];
        for (const k of kinds) {
            const target = best ? Math.round(best.defenses[k] * 1.08) : Math.round(def.defenses[k] * 1.15);
            if (target > def.defenses[k]) def.defenses[k] = target;
        }
    }
    if (def.damage && (def.slotType === 'weapon' || def.slotType === 'ranged')) {
        const hands = def.hands || 1;
        const comp = bases.filter(b => b.damage && (def.slotType === 'ranged' || (b.hands || 1) === hands));
        const ranged = def.slotType === 'ranged';
        const dps = (dmg, iv) => ((dmg.min + dmg.max) / 2) / (iv || 1);
        const bestDps = Math.max(0, ...comp.map(b => dps(b.damage, ranged ? 1 : b.attackIntervalSeconds)));
        const mine = dps(def.damage, ranged ? 1 : def.attackIntervalSeconds);
        if (bestDps > 0 && mine < bestDps * 1.05) {
            const f = Math.min(2.5, bestDps * 1.05 / mine);
            def.damage = { min: Math.round(def.damage.min * f), max: Math.round(def.damage.max * f) };
        }
    }
    if (def.slotType === 'shield') {
        const bestBlock = Math.max(0, ...bases.map(b => b.blockChance || 0));
        if (bestBlock + 2 > (def.blockChance || 0)) def.blockChance = bestBlock + 2;
    }
}

// Fate is very strong: at most 3% per item below level 45, 5% above, so a full
// set of gear stays around 40-50%.
function capFate(def) {
    const cap = (def.minLevel || 1) < 45 ? 3 : 5;
    for (const b of def.bonuses || []) {
        if (b.key === 'fate' && b.value > cap) b.value = cap;
        // Raising a resistance cap is extremely strong: at most +3% per item.
        if (/^max_.*res$/.test(b.key) && b.value > 3) b.value = 3;
    }
}

// Timer values on uniques. Map timers run for minutes and the passive tree
// pays out timer seconds in the tens to hundreds, so single-digit seconds on a
// unique are not noticeable. Values below the floor for the item's level are
// raised to it (explicitly authored larger values are kept).
function timerFloor(level, tiers) { return level < 20 ? tiers[0] : level < 40 ? tiers[1] : level < 60 ? tiers[2] : tiers[3]; }
const TIMER_FLOORS = {
    first_step_time: [30, 60, 60, 60],
    quiz_time: [60, 60, 90, 120],
    time_on_kill: [10, 10, 15, 20],
    time_on_elite: [45, 45, 60, 90],
    freeze_timer_on_stun: [3, 3, 3, 4],
};
function normalizeTimers(def) {
    const level = def.minLevel || 1;
    if (Array.isArray(def.effects)) {
        def.effects = def.effects.map(spec => {
            const [key, val] = spec.split(':');
            const tiers = TIMER_FLOORS[key];
            if (!tiers) return spec;
            const floor = timerFloor(level, tiers);
            return Number(val) < floor ? `${key}:${floor}` : spec;
        });
    }
    for (const b of def.bonuses || []) {
        // +Puzzle Time lines: regular affixes top out at 60s; uniques pay minutes.
        if (b.key === 'time_added' && b.value > 0 && b.value < 90) b.value = Math.min(300, Math.max(90, Math.round(b.value * 3 / 5) * 5));
    }
    for (const d of def.downsides || []) {
        // A Puzzle Time downside has to cost minutes to be a cost at all.
        if (d.key === 'time_added' && d.value < 0 && -d.value < 60) d.value = -timerFloor(level, [90, 90, 120, 150]);
    }
}

// Applies the rework table onto the base definition array (mutates entries in
// place so importers see the reworked stats). Returns the number applied;
// unknown keep keys are collected in EG_UNIQUE_REWORK_PROBLEMS (tested).
export const EG_UNIQUE_REWORK_PROBLEMS = [];
export function applyUniqueReworks(items) {
    let applied = 0;
    EG_UNIQUE_REWORK_PROBLEMS.length = 0;
    for (const def of items) {
        const rework = EG_UNIQUE_REWORKS[def.uniqueId];
        if (!rework) continue;
        if (Array.isArray(rework)) {
            generateStats(def, rework, EG_UNIQUE_REWORK_PROBLEMS);
        } else {
            delete def.downsides;
            delete def.effects;
            Object.assign(def, rework, { v2: true });
        }
        capFate(def);
        normalizeTimers(def);
        upgradeBase(def);
        applied++;
    }
    return applied;
}
