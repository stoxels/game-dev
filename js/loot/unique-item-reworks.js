// Unique item REWORKS (v2). Data only.
//
// The original 303 uniques (unique-item-data.js) were written with 2-4 stat
// lines, low numbers and a heavy downside on nearly every item, so almost none
// beat a decent epic. This file holds the systematic rebalance: each entry
// REPLACES the stat block (bonuses / downsides / defenses) of the unique with
// the same uniqueId and may add passive-tree style `effects`. Names, icons,
// requirements and flavor text stay untouched in the original file.
//
// Design rules (checked by dev/tests/unique-audit.test.mjs):
//   - at least 5 value lines (stat lines + effects + special lines)
//   - at most ONE downside, and a mild one (<= ~35% of the upside)
//   - `role` is one of:
//       bis      best-in-slot stat stick, little or no downside
//       synergy  pairs with a passive-tree mechanic (effects)
//       mild     a modest new mechanic on top of good stats
//       wild     build-defining: keystone-class effect, sometimes a trade-off
//   - numbers sit at roughly 70-100% of the best regular affix tier that is
//     unlocked at the item's level (see dev/scratch/affix-ref.md, generated by
//     the audit), and base defenses match the best regular base of the slot.
//
// `effects` use the passive-tree effect registry (pt-effects.js), e.g.
// "damage_per_streak:6". They add to the same stat channels as tree nodes, so
// uniques stack with the tree and tooltips are generated from the registry.
// Label placeholders: '#' = signed value, '{a}' = absolute value.

